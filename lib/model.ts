// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// pre-token protocols below the watchlist floor with the most TVL: the early rows the radar exists to
// find. A protocol is pre-token when its index entry records no token (no market cap, no CoinGecko id,
// no symbol); the snapshot's live-token protocols are kept apart and shown as the market's own values,
// never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures:
//
//   categoryMultiple = median(mcap_usd / tvl_usd) over the live-token protocols in the same
//                      category, computed from this snapshot (at least 3 samples, else the
//                      global median over all live-token protocols), clamped to [0.05, 1.0]
//   base             = tvl_usd x categoryMultiple
//   growthMult       = 1 + clamp(change_7d, -50, 100) / 100 x 0.5
//   maturityMult     = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365 days)
//   breadthMult      = 1 + 0.05 x min(chains - 1, 4)
//   implied          = max(1, round(base x growthMult x maturityMult x breadthMult))
//
// The market's own pricing calibrates the model: a category whose tokens already trade at a high
// multiple of TVL (DEXs, basis trading) implies more value per TVL dollar than one whose tokens trade
// cheap (lending, liquid staking). No protocol name is ever special-cased: the same function scores
// every row, and the multiples are recomputed from whatever snapshot is handed in.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

